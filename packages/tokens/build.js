/**
 * @file Builds Pumpkin Spice design tokens with Style Dictionary.
 *
 * Token source lives in ./tokens as W3C DTCG JSON. Every output uses the
 * `psds` prefix, so `color.brand.primary` becomes `--psds-color-brand-primary`.
 * One output is written outside this package, to ../../src/foundation, so the
 * Emulsify system ships the same custom properties to Drupal projects.
 */

import StyleDictionary from 'style-dictionary';

const sd = new StyleDictionary({
  source: ['tokens/**/*.json'],
  usesDtcg: true,
  log: { verbosity: 'default' },
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: 'psds',
      buildPath: 'dist/css/',
      files: [{ destination: 'tokens.css', format: 'css/variables' }],
    },
    scss: {
      transformGroup: 'scss',
      prefix: 'psds',
      buildPath: 'dist/scss/',
      files: [{ destination: '_tokens.scss', format: 'scss/variables' }],
    },
    js: {
      transformGroup: 'js',
      buildPath: 'dist/js/',
      files: [{ destination: 'tokens.js', format: 'javascript/es6' }],
    },
    json: {
      transformGroup: 'js',
      buildPath: 'dist/json/',
      files: [{ destination: 'tokens.json', format: 'json/nested' }],
    },
    // Emulsify/Drupal: CSS custom properties written as a Sass partial in the
    // system's foundation directory, which `emulsify system install` copies.
    emulsify: {
      transformGroup: 'css',
      prefix: 'psds',
      buildPath: '../../src/foundation/',
      files: [
        {
          destination: '_tokens.scss',
          format: 'css/variables',
          options: { fileHeader: 'psdsGenerated' },
        },
      ],
    },
  },
  hooks: {
    fileHeaders: {
      psdsGenerated: () => [
        'Generated by packages/tokens. Do not edit directly.',
        'Edit packages/tokens/tokens/*.json and run `npm run tokens`.',
      ],
    },
  },
});

await sd.cleanAllPlatforms();
await sd.buildAllPlatforms();
