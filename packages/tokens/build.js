/**
 * @file Builds Pumpkin Spice design tokens with Style Dictionary.
 *
 * Token source lives in ./tokens as W3C DTCG JSON. Every output uses the
 * `psds` prefix, so `color.brand.primary` becomes `--psds-color-brand-primary`.
 */

import StyleDictionary from 'style-dictionary';

/**
 * Maps a token to a Tailwind v4 theme variable name, or null to leave it out.
 * Raw palette colors and border widths are skipped so utilities stay on the
 * semantic tokens (bg-brand-primary, not bg-pumpkin-700).
 */
function tailwindThemeName(token) {
  const [group, ...rest] = token.path;
  const name = rest.join('-');

  if (group === 'color') {
    return rest[0] === 'palette' ? null : `--color-${name}`;
  }
  if (group === 'space') {
    // Tailwind derives p-4, gap-2, etc. from one base unit: calc(var(--spacing) * n).
    return rest[0] === '1' ? '--spacing' : null;
  }
  if (group === 'radius') return `--radius-${name}`;
  if (group === 'font') {
    const [kind, ...key] = rest;
    const prefixes = {
      family: '--font-',
      weight: '--font-weight-',
      size: '--text-',
      'line-height': '--leading-',
    };
    return prefixes[kind] ? `${prefixes[kind]}${key.join('-')}` : null;
  }
  return null;
}

StyleDictionary.registerFormat({
  name: 'tailwind/theme',
  format: ({ dictionary }) => {
    const lines = dictionary.allTokens
      .map((token) => [tailwindThemeName(token), token.name])
      .filter(([themeName]) => themeName)
      .map(([themeName, cssName]) => `  ${themeName}: var(--${cssName});`);

    return [
      '/**',
      ' * Generated by packages/tokens. Do not edit directly.',
      ' * Tailwind v4 theme mapped onto the --psds-* custom properties. `inline`',
      ' * makes utilities reference those properties, so overriding a --psds-*',
      " * value restyles every utility that uses it. Tailwind's default colors,",
      ' * radii, and type scale are cleared so only Pumpkin Spice tokens exist.',
      ' */',
      '@theme inline {',
      '  --color-*: initial;',
      '  --radius-*: initial;',
      '  --font-*: initial;',
      '  --text-*: initial;',
      '  --leading-*: initial;',
      ...lines,
      '}',
      '',
    ].join('\n');
  },
});

const sd = new StyleDictionary({
  source: ['tokens/**/*.json'],
  usesDtcg: true,
  log: { verbosity: 'default' },
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: 'psds',
      buildPath: 'dist/css/',
      files: [{ destination: 'tokens.css', format: 'css/variables' }],
    },
    js: {
      transformGroup: 'js',
      buildPath: 'dist/js/',
      files: [{ destination: 'tokens.js', format: 'javascript/es6' }],
    },
    json: {
      transformGroup: 'js',
      buildPath: 'dist/json/',
      files: [{ destination: 'tokens.json', format: 'json/nested' }],
    },
    tailwind: {
      transformGroup: 'css',
      prefix: 'psds',
      buildPath: 'dist/tailwind/',
      files: [{ destination: 'theme.css', format: 'tailwind/theme' }],
    },
  },
});

await sd.cleanAllPlatforms();
await sd.buildAllPlatforms();
